class PIDGen():
    """
    PID generator.
    """
    
    @staticmethod
    def gen_pid(nid, sid, pido, sk, px):
        """ Returns a PID. PID = hash(nid, sid, pido, sk, px) | px where hash=md5

        :param nid: of type NID, 16 bytes, example: nid=0x11223344556677889900AABBCCDDEEFF
        :param sid: of type SID, 36 bytes, example: 
            sid=0x11223344556677889900AABBCCDDEEFF11223344556677889900AABBCCDDEEFF11223344
        :param pido: of type int, 4 bytes, example: pido=0x1234CDEF
        :param sk: of type SK, 4 bytes, example: sk=0xABCDEF12
        :param px: of type PX, 2 bytes, example: px=0x1234

        For the example given above, content to be hashed is:
        11223344556677889900AABBCCDDEEFF11223344556677889900AABBCCDDEEFF112233445566
        77889900AABBCCDDEEFF11223344EFCD341212EFCDAB3412,
        the returned PID is 0x1234BB18.
        """
        data = nid.to_bytes(byteorder="big") + sid.to_bytes(byteorder="big") + \
            (pido.to_bytes(4, byteorder="little", signed=False) if pido != 0 else b'') + \
            sk.to_bytes(byteorder="little") + px.to_bytes(byteorder="little")
        d = md5(data).digest()
        pid = px.int_value << 16 | d[-1] << 8 | d[-2]
        return pid
    
    @staticmethod
    def gen_pids(nid, sid, sks, pxs):
        """Returns a sequence of PIDs

        :param nid: 16 bytes, example: nid=0x11223344556677889900AABBCCDDEEFF
        :param sid: 36 bytes, example: 
            sid=0x11223344556677889900AABBCCDDEEFF11223344556677889900AABBCCDDEEFF11223344
        :param sks: a list of SK(4 bytes), example: sks=[0xAAAABBBB, 0xCCCCDDDD, 0xEEEEFFF]
        :param pxs: a list of PX(2 bytes), example: pxs=[0x1234, 0x5678, 0xABCD]

        The length of sks should be equal to the length of pxs. 
        For the above example, the returned pids=[0x12341f8d, 0x5678321d, 0xabcd7798]
        """
        pids = [PIDGen.gen_pid(nid, sid, 0, sks[0], pxs[0])]
        for i in range(1, len(sks)):
            pids.append(PIDGen.gen_pid(nid, sid, pids[i-1], sks[i], pxs[i]))
        return pids

class PX:
    generated_pxs = set()
    def __init__(self, px):
        """
        :param px: of type int or str, string is interpreted as hexadecimals

        Examples: PX(0x1122), PX('0x9999')
        """
        if isinstance(px, int):
            self.__px = px
        elif isinstance(px, str):
            self.__px = int(px, base=16)
        else:
            raise TypeError("'px' can only be int or str")
        
        if self.__px > 0xFFFF:
            raise ValueError("'px' should be a 16-bit value")

    def __str__(self):
        return "%04X" % self.__px
    
    @property
    def int_value(self):
        return self.__px
    
    def to_bytes(self, byteorder="little"):
        return self.__px.to_bytes(2, byteorder=byteorder, signed=False)

    def __eq__(self, other):
        if isinstance(other, PX):
            return (self.__px == other.__px)
        return False

    def __hash__(self):
        return hash(self.__px)

    @staticmethod
    def random():
        for _ in range(int(7e5)):
            px = PX(random.getrandbits(16))
            if not (px in PX.generated_pxs):
                PX.generated_pxs.add(px)
                return px
        raise Exception("Cannot generated more PX.")

class SK:
    def __init__(self, sk):
        self.__sk = sk
        """
        :param sk: of type int or str, string is interpreted as hexadecimals

        Examples: SK(0x11223344), SK('0x99998888')
        """
        if isinstance(sk, int):
            self.__sk = sk
        elif isinstance(sk, str):
            self.__sk = int(sk, base=16)
        else:
            raise TypeError("'sk' can only be int or str")
        
        if self.__sk > 0xFFFFFFFF:
            raise ValueError("'sk' should be a 32-bit value")
    
    def __str__(self):
        return "%08X" % self.__sk
    
    def to_bytes(self, byteorder="little"):
        return self.__sk.to_bytes(4, byteorder=byteorder, signed=False)

    def cfg_str(self):
        return "sk %08X" % self.__sk
    
    @staticmethod
    def random():
        return SK(random.getrandbits(32))

class NID:
    __num_lower_bits = 128 - 32

    def __init__(self, nid):
        """
        :param nid: nid is of type int, 128 bit
        """
        self.__nid = nid
    
    def __str__(self):
        return "%032X" % self.__nid
    
    def to_string(self, sep='-'):
        s = "%02X" % (self.__nid >> (128 - 8))
        for i in range(1, 16):
            s += sep + "%02X" % ( (self.__nid >> (128 - 8 * (i + 1))) & 0xFF )
        return s

    def to_bytes(self, byteorder='big'):
        return self.__nid.to_bytes(16, byteorder=byteorder, signed=False)

    @staticmethod
    def random(asid=None):
        lowerbits = random.getrandbits(NID.__num_lower_bits)
        if asid is None:
            asid = random.getrandbits(32)
        return NID(lowerbits | asid << (NID.__num_lower_bits))

