class GET(Packet):
    """
    Value of the following fields must be supplied:
        pids, flags, n_sid, l_sid, nid, minimal_pid_cp, mtu
        
        1. pids can be an empty list.
        2. Default flags is 0x0.
        3. minimal_pid_cp and mtu are set to 0 if those values are not specified.
     
    Value of optional fields can be provided if you wish:
    (Dont't forget to set the flags)
        qos_req, public_key, seg_id
    
    Advance usage: You may modify those values that are automatically set.
    Change the following fields may generate malformed packets.
        ttl, pkg_len, cksum, pid_num, qos_len, public_key_len
    
    Examples: Suppose n_sid, l_sid, nid is defined elsewhere (not cared).
    Note that n_sid, l_sid, nid is of class 'bytes'. Numbers can be converted
    by to_bytes().
    nid=(0x11223344556677889900AABBCCDDEEFF).to_bytes(16, byteorder='big', signed=False)
    
        1. Create a GET packet from other AS with no optional fields.
            p = GET(pids=[0x1122DBA2, 0x33445fD6], flags="F+A", minimal_pid_cp=300,
                mtu=1200, n_sid=n_sid, l_sid=l_sid, nid=nid) 
            There are two PIDs in this case. No need to set pid_num=2 because 
            pid_num can be inferred by pids automatically. Flag "F" is set, which 
            means that the GET packet is from other AS. Flag "A" indicates ACK is 
            supported. This packet may have gone through 2 ASes and is about to sent 
            to the next border router.
        2. Create a GET packet with optional fields
            p = GET(pids=[0x1122DBA2, 0x33445fD6], flags="F+A+S+K+Q", 
                seg_id=0, n_sid=n_sid, l_sid=l_sid, nid=nid, seg_id=12, 
                public_key="This is public key", qos_req="This is QoS field") 
        3. Create a minimal GET packet.
            p = GET(pids=[], n_sid=n_sid, l_sid=l_sid, nid=nid) 
            No flags are set. No optional fields. mtu and minimal_pid_cp is set
            to 0. This GET packet may be generated by the consumer.

    Detailed description of fields in DATA packet:
        ttl: default value is 64
        pkg_len: this field is calculated automatically 
        cksum: this field is calculated automatically 
        mtu: maximum transmission unit, default value is 0
        pid_num: this field is calculated automatically
        flags: default value is 0x0, available flags includes "A", "S", "Q", "K", "F"
               1. The GET packet is from other AS if "F" is set, 
               2. ACK is supported if "A" is set.
               3. "S": segment ID
               4. "Q": QoS
               5. "K": public key
        minimal_pid_cp: default value is 0
        n_sid: No default value
        l_sid: No default value
        nid: No default value
        qos_len: this field is calculated automatically, set flag "Q" when qos_len is used
        qos_req: value of this field should be supplied by user, set flag "Q" when qos_req is used
        public_key_len: this field is calculated automatically, set flag "K" when qos_len is used
        public_key: value of this field should be supplied by user, set flag "K" when qos_req is used
        seg_id: default value is 0, set flag "S" when seg_id is used
        pids: PID sequence, a list, pid_num is auto-generated by pids
    """
    name = "GET"
    fields_desc = [
        BitField("version", 7, 4),
        BitField("package", 2, 4),
        ByteField("ttl", 64),
        LEShortField("pkg_len", None),
        XLEShortField("cksum", None),
        LEShortField("mtu", None),
        FieldLenField("pid_num", None, fmt="B", count_of="pids"),
        FlagsField("flags", 0x0, 8, ["r0", "r1", "r2", "A", "S", "Q", "K", "F"]),
        LEShortField("minimal_pid_cp", None),
        StrFixedLenField("n_sid", None, 16),
        StrFixedLenField("l_sid", None, 20),
        StrFixedLenField("nid", None, 16),
        ConditionalField(FieldLenField("public_key_len", None, fmt="<H", 
            length_of="public_key"), lambda pkt: "K" in pkt.flags),
        ConditionalField(StrLenField("public_key", None, length_from="public_key_len"), 
            lambda pkt: "K" in pkt.flags),
        ConditionalField(FieldLenField("qos_len", None, fmt="B", length_of="qos_req", 
            adjust=lambda pkt, x: x * 8), lambda pkt: "Q" in pkt.flags),
        ConditionalField(StrLenField("qos_req", None, length_from="qos_len"), 
            lambda pkt: "Q" in pkt.flags),
        ConditionalField(LEIntField("seg_id", 0), lambda pkt: "S" in pkt.flags),
        FieldListField("pids", None, XLEIntField("", 0x0), count_from=lambda pkt: pkt.pid_num),
    ]

    def post_build(self, p, pay):
        if self.pkg_len is None:
            pkg_len = len(p) + len(pay)
            p = p[:2] + chb(pkg_len & 0xff) + chb(pkg_len >> 8) + p[4:]
        if self.cksum is None:
            ck = checksum(p)
            p = p[:4] + chb(ck & 0xff) + chb(ck >> 8) + p[6:]
        return p + pay

