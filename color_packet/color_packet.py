class Proxy:
    """ Proxy is used to describe topology when generating configuation file 
    and traffic for testing border router. Specify parent AS and IP address 
    in constructor. ip_address can be omitted if the proxy is not in the same
    domain with target border router. Proxy's NID will be randomly generated.
    """
    def __init__(self, of, ip_address=(0, 0, 0, 0), num_sid=1):
        """
        :param of: AS to which the proxy belongs
        :param ip_address: A tuple represent IP address, e.g., (10, 1, 1, 2)
        :param num_sid: The number of SID registered by this proxy, >= 1.
        """
        self.parent_as = of
        self.nid = NID.random(self.parent_as.id)
        self.ip_address = IPAddress(ip_address)
        self.sk = random.getrandbits(256)
        self.sid_list = []
        self.parent_as.add_proxy(self)
        for _ in range(num_sid):
            self.sid_list.append(SID(self.nid, LSID.random(self.parent_as.id)))

    def __str__(self):
        return "nid %s %s %064X" % (self.nid, self.ip_address, self.sk)
    
    def cfg_str(self):
        return self.__str__()
    
    def random_sid(self):
        return random.choice(self.sid_list)
    
    def nid_entry(self):
        return (str(self.nid), str(self.ip_address), "%064X" % self.sk)

class BorderRouter:
    """ BorderRouter is used to describe topology when generating configuation file 
    and traffic for testing border router. """
    def __init__(self, of):
        """
        :param of: AS to which the border router belongs
        """
        self.parent_as = of
        self.nid = NID.random(self.parent_as.id)
        self.sk = random.getrandbits(32 * 8) # 32 bytes
        self.parent_as.add_br(self)
        self.__port_dict = {}
        self.direct_interdomain_path = []
        self.indirect_interdomain_path = []
        self.__iproute_list = []
    
    def sk_bytes(self):
        return int.to_bytes(self.sk, length=32, byteorder='big')
    
    def get_dip_to(self, br):
        """ direct interdomain path """
        for interdomain_path in self.direct_interdomain_path:
            if br is interdomain_path.to_br:
                return interdomain_path

    def get_iip_to(self, br):
        """ indirect interdomain path """
        for interdomain_path in self.indirect_interdomain_path:
            if br is interdomain_path.to_br:
                return interdomain_path

    def add(self, port):
        """ Add a port for this border router. 
        :param port: Port of target border router or border routers connected to 
        target border router must have ip_address and mask_length configured. 
        Other border router do not need ip_address and mask_length, these two 
        arguments can be omitted.
        """
        self.__port_dict[port.id] = port
    
    def add_iproute(self, iproute):
        """ Add a static route entry in border router's IP routing table.
        Only target border router requires static route entries.
        """
        self.__iproute_list.append(iproute)

    def port(self, id):
        return self.__port_dict[id]

    def add_interdomain_path(self, path, is_direct):
        """ This method can only be called by the constructor of InterdomainPath. """
        if is_direct:
            self.direct_interdomain_path.append(path)
        else:
            self.indirect_interdomain_path.append(path)

    def __port_cfg(self):
        port_cfg = "#\n"
        for port in self.__port_dict.values():
            port_cfg += port.cfg_str() + "\n"
        return port_cfg
    
    def __iproute_cfg(self):
        iproute_cfg = "#\n"
        for iproute in self.__iproute_list:
            iproute_cfg += iproute.cfg_str() + "\n"
        return iproute_cfg
    
    def __arp_cfg(self):
        """ Generate ARP entries for RM, connected border routers"""
        arp_cfg = "#\n"
        ip_list = {self.parent_as.rm.ip_address}
        ip_list |= {iip.to_port.ip_address for iip in self.indirect_interdomain_path}
        ip_list |= {dip.to_port.ip_address for dip in self.direct_interdomain_path}
        ip_list |= {iproute.next_hop for iproute in self.__iproute_list}
        # ip_list |= {proxy.ip_address for proxy in self.parent_as.proxy_list}
        for ip_address in ip_list:
            arp_cfg += "arp add F8F21E%06X %s\n" % (random.getrandbits(24), ip_address)
        return arp_cfg

    def __peer_cfg(self):
        cfg = "#\n"
        path_cfg = ""
        peer_list = []
        for path in self.direct_interdomain_path + self.indirect_interdomain_path:    
            s = "peer add %s %s sk %064X" \
                % (path.peer_type, path.to_port.ip_address, path.to_br.sk)
            if not s in peer_list:
                peer_list.append(s)
            path_cfg += path.path_cfg() + "\n"
        for p in peer_list:
            cfg += p + "\n"
        return cfg + path_cfg

    def __odc_cfg(self):
        odc_cfg = "#\nodc enable\n"
        return odc_cfg

    def cfg_str(self):
        """
        :param consumer_nid_list: A list of NID used to generate ODC table.
        """
        cfg = "read-only on\n"
        cfg += "#\nsysname BR\n"
        cfg += "#\nbr-nid %s\n" % self.nid.to_string(sep="-")
        cfg += "#\ndebugging off\n"
        rm_sk_cfg = self.parent_as.cfg_str()
        cfg += rm_sk_cfg + self.__port_cfg() + self.__iproute_cfg() \
            + self.__arp_cfg() + self.__peer_cfg() + self.__odc_cfg()
        return cfg
    
    def nid_entries(self):
        return self.parent_as.nid_entries()
    
class InterdomainPath:
    """ InterdomainPath is used to describe topology when generating configuation 
    file and traffic for testing border router. InterdomainPath represents how 
    ASes are connected. InterdomainPath has a direction. 
    A InterdomainPath is a direct InterdomainPath if to_br.parent_as == to_as.
    A InterdomainPath is an indirect InterdomainPath if to_br.parent_as != to_as.
    Both direct and indirect InterdomainPath should be added manually.
    """
    def __init__(self, from_br, from_port_id, to_br, to_port_id, to_as, px=None):
        self.to_br = to_br
        self.to_port = to_br.port(to_port_id)
        self.from_port = from_br.port(from_port_id)
        self.to_as = to_as
        self.px = PX.random() if px is None else px
        self.is_direct = to_br.parent_as is to_as
        self.from_br = from_br
        self.peer_type = "external" if self.is_direct else "internal"
        from_br.add_interdomain_path(self, is_direct=self.is_direct)
    
    def path_cfg(self):
        return "peer add-path %s as %d px %04X0000/%d" \
            % (self.to_port.ip_address, self.to_as.id, self.px.int_value, 16)

class AutonomousSystem:
    """ AutonomousSystem is used to describe topology when generating configuation 
    file and traffic for testing border router."""
    def __init__(self, id, rm, sk=None):
        """
        :param id: An integer
        :param rm: A ResourceManager object. 
        :param sk: A SK object. If param sk is omitted, SK of the AS will be randomly generated.
        """
        self.id = id
        self.sk = SK.random() if sk is None else sk
        self.rm = rm
        self.proxy_list = []
        self.br_list = []

    @property
    def nid_list(self):
        """ Returns a list of proxy's NID in this AS. """
        return [proxy.nid for proxy in self.proxy_list]

    @property
    def sid_list(self):
        """ Returns a list of SID in this AS. """
        sid_list = []
        for proxy in self.proxy_list:
            sid_list.extend(proxy.sid_list)
        return sid_list
    
    def nid_entries(self):
        """ Returns NID entries in this AS. NID entries can be added to database. """
        nid_entries = []
        for proxy in self.proxy_list:
            nid_entries.append(proxy.nid_entry())
        return nid_entries

    def add_proxy(self, proxy):
        """ This method is called by Proxy's constructor. """
        self.proxy_list.append(proxy)
    
    def add_br(self, br):
        """ This method is called by BorderRouter's constructor. """
        self.br_list.append(br)
    
    def cfg_str(self):
        """ Returns the RM, SK and NID configuration for BR in this AS. """
        rm_cfg = "#\n%s\n" % self.rm.cfg_str()
        sk_cfg = "#\n%s\n" % self.sk.cfg_str()
        return rm_cfg + sk_cfg
    
    def random_proxy(self):
        """ Randomly choose a Proxy. """
        return random.choice(self.proxy_list)

class IIPGen:
    """ IIPGen(Indirect interdomain path generator) is used to generating 
    configuation file and traffic for testing border router. IIPGen provides 
    methods to generate indirect interdomain path. Methods here can only be 
    called after all direct interdomain paths are declared.
    """
    @staticmethod
    def gen_iip_for_br_pair(br1, br1_port_id, br2, br2_port_id):
        """
        Generate indirect interdomain path for a pair of border router.
        br1 and br2 belong to the same AS. No order is required for br1 and br2.
        br1_port_id can reach br2_port_id.
        """
        br1_dip_list = br1.direct_interdomain_path
        br2_dip_list = br2.direct_interdomain_path
        for dip in br1_dip_list:
            InterdomainPath(from_br=br2, from_port_id=br2_port_id, to_br=br1, \
                to_port_id=br1_port_id, to_as=dip.to_as, px=dip.px)
        for dip in br2_dip_list:
            InterdomainPath(from_br=br1, from_port_id=br1_port_id, to_br=br2, \
                to_port_id=br2_port_id, to_as=dip.to_as, px=dip.px)
    
    @staticmethod
    def gen_iip_for_target_br(target_br, target_br_port_id, peer_br_port_id):
        """
        target_br_port_id is connected to peer_br_port_id.
        """
        br_list = target_br.parent_as.br_list
        for peer_br in br_list:
            if peer_br is not target_br:
                IIPGen.gen_iip_for_br_pair(br1=target_br, br1_port_id=target_br_port_id, \
                    br2=peer_br, br2_port_id=peer_br_port_id)

class TrafficGen:
    """
    TrafficGen(Traffic generator) is used to generate traffic for testing border 
    router.
    """

    COLOR_PROTO = 150

    @staticmethod
    def __pids_to_hex_str(pid_seq):
        s = ""
        for pid in pid_seq:
            s += "%08X" % int.from_bytes(pid.to_bytes(length=4, byteorder="little", signed=False), byteorder="big")
        return s

    @staticmethod
    def __extract_px_sk(path):
        """ Return (px_list, sk_list).
        :param target_br: Target border router is where traffic goes to.
        :param path: A list of AS and BR specifying the path of traffic. 
        Example: [as1, br11, br21, as2, br22, br31, as3]
        """
        px_list = []
        sk_list = []
        n = int((len(path) - 1) / 3) # len(path) = 3n + 1
        for i in range(0, n):
            as_from = path[i * 3]
            br_from = path[i * 3 + 1]
            br_to = path[i * 3 + 2]
            px_list.append(br_from.get_dip_to(br_to).px)
            sk_list.append(as_from.sk)
        sk_list.append(path[-1].sk) # SK of the last AS
        return (px_list, sk_list)

    @staticmethod
    def __extract_idp(target_br, path):
        """ Return (interdomain_path, index_of_target_br).
        :param target_br: Target border router is where traffic goes to.
        :param path: A list of AS and BR specifying the path of traffic. 
        Example: [as1, br11, br21, as2, br22, br31, as3]
        """
        n = int((len(path) - 1) / 3) # len(path) = 3n + 1
        last_br = None
        current_br = path[1]
        if current_br is target_br: # no interdomain path
            return (None, 1)
        for i in range(0, n):
            for j in [1, 2]:
                index = i * 3 + j
                current_br = path[index]
                if current_br is target_br:
                    # last_br send packet to current_br(target)
                    if j == 1:
                        return last_br.get_iip_to(current_br), index
                    else: # j == 2
                        return last_br.get_dip_to(current_br), index
                last_br = current_br

    @staticmethod
    def gen_get_traffic(target_br, target_port_id, path, num_pkts=100):
        """ Return a list of GET packets.
        :param target_br: Target border router is which traffic goes to.
        :param target_port_id: the port which traffic goes to
        :param path: A list of AS and BR specifying the path of traffic. 
        :param num_pkt: Number of packets in returned list.

        Example: path=[as1, br11, br21, as2, br22, br31, as3]
                        ^                                 ^
                     consumer     ---GET packet-->     provider
        
        px_list = [px_12, px_23]
        sk_list = [sk_1, sk_2, sk_3]

        Case 1: target_br=br11
            [as1, br11, br21, as2, br22, br31, as3]
                   ^
                target_br(index=1), num_pids=1, from the same domain(do not set flag F)
        
        Case 2: target_br=br21
            [as1, br11, br21, as2, br22, br31, as3]
                         ^
                    target_br(index=2), num_pids=1, from other domain(set flag F)

        Case 3: target_br=br22
            [as1, br11, br21, as2, br22, br31, as3]
                                    ^
                                target_br(index=4), num_pids=2, do not set flag F
        
        Case 4: target_br=br31
            [as1, br11, br21, as2, br22, br31, as3]
                                          ^
                                     target_br(index=5), num_pids=2, set flag F
        
        Condition for set flag F: index_of_target_br % 3 == 2
        """
        as_consumer, as_provider = path[0], path[-1]
        px_list, sk_list = TrafficGen.__extract_px_sk(path)
        idp, index_of_target_br = TrafficGen.__extract_idp(target_br, path)
        is_inbound = index_of_target_br % 3 == 2
        if is_inbound:
            src_ip = str(idp.from_port.ip_address)
        else: # outbound packets' source IP address is RM's IP address
            src_ip = str(target_br.parent_as.rm.ip_address)
        dst_ip = str(target_br.port(target_port_id).ip_address)
        num_pids = int(index_of_target_br / 3) + 1
        flags = "F" if is_inbound else "" # F: from other domain
        pkts = []
        for _ in range(num_pkts):
            nid = as_consumer.random_proxy().nid
            sid = as_provider.random_proxy().random_sid()
            pids = PIDGen.gen_pids(nid, sid, sks=sk_list[0:num_pids], \
                pxs=px_list[0:num_pids])
            pkt = Ether() / IP(src=src_ip, dst=dst_ip)\
                / GET(pids=pids, flags=flags, nid=nid.to_bytes(), \
                n_sid=sid.nsid.to_bytes(), l_sid=sid.lsid.to_bytes())
            pkts.append(pkt)
        return pkts
    
    @staticmethod
    def gen_data_traffic(target_br, target_port_id, path, odc_dict, num_pkts=100, \
        pld_size=1000, back_pid=True):
        """ Return a list of DATA packets.
        :param target_br: Target border router is where traffic goes to.
        :param path: A list of AS and BR specifying the path of traffic. 
        :param num_pkt: Number of packets in returned list.
        :param pld_size: size of payload for DATA packet, default value is 1000
        :param back_pid: if back_pid is true, set flag R
        
        Example: path=[as1, br11, br21, as2, br22, br31, as3]
                        ^                                 ^
                    provider     ---DATA packet-->     consumer
        
        px_list = [px_12, px_23]
        sk_list = [sk_1, sk_2, sk_3]
        num_pids = 2

        REVERSE px_list and sk_list when calculating PID sequence
        i.e., pxs = [px_23, px_12], sks = [sk_3, sk_2]
        forward PID sequence = [PID23, PID12]

        DON'T REVERSE px_list and sk_list when calculating backward PID sequence
        i.e., pxs = [px_12, px_23], sks = [sk_1, sk_2]
        backward PID sequence = [PID21, PID32] 

        Case 1: target_br=br11

            [as1, br11, br21, as2, br22, br31, as3]
                   ^
               target_br(index=1), from the same domain(do not set flag F)
            
            PID sequence = [PID23, PID12, NULL]
                                    ^
                                pid_pt=2

        Case 2: target_br=br21

            [as1, br11, br21, as2, br22, br31, as3]
                         ^
                    target_br(index=2), from other domain(set flag F)
            
            PID sequence = [PID23, PID12, PID21]
                                    ^
                                pid_pt=2

        Case 3: target_br=br22

            [as1, br11, br21, as2, br22, br31, as3]
                                    ^
                                target_br(index=4), do not set flag F
            
            PID sequence = [PID23, PID12, PID21]
                             ^
                          pid_pt=1
        
        Case 4: target_br=br31
        
            [as1, br11, br21, as2, br22, br31, as3]
                                          ^
                                      target_br(index=5), set flag F
            
            PID sequence = [PID23, PID32, PID21]
                             ^
                          pid_pt=1
        
        Condition for set flag F: index_of_target_br % 3 == 2
        If back_pid is true, PID sequence in packets is obtained as follows.
        To make things easier, add a null pointer in PID sequence first:
            pid_seq = [PID23, PID12, 0]
            backward PID sequence = [PID32, PID21]
            Length of pid_seq is num_pids + 1.
        The number of backward PIDs that overwrite pid_seq is:
            floor(index_of_target_br / 2) - floor(index_of_target_br / 3)
        
        Pass pid_seq[0:-1] to pids parameter(index starts at 0), pass pid_seq[-1] 
        to res_pid parameter when constructing DATA packets.
        """
        as_provider, as_consumer = path[0], path[-1]
        px_list, sk_list = TrafficGen.__extract_px_sk(path)
        idp, index_of_target_br = TrafficGen.__extract_idp(target_br, path)
        # S: segment ID, R: reserved PID, F: from other domain, C: HMAC
        is_inbound = index_of_target_br % 3 == 2
        is_odpfip = (index_of_target_br == 1) # outbound data packet from in-domain proxy
        src_ip = str(idp.from_port.ip_address) if idp is not None else None
        dst_ip = str(target_br.port(target_port_id).ip_address)
        flags = "S+C" + ("+R" if back_pid else "") + ("+F" if is_inbound else "")
        num_pids = len(px_list)
        pid_pt = num_pids - int(index_of_target_br / 3)
        num_overwrite = int(index_of_target_br / 2) - int(index_of_target_br / 3) # backward PID
        pkts = []
        odc_entries = []
        for _ in range(num_pkts):
            nid = as_consumer.random_proxy().nid
            proxy_provider = as_provider.random_proxy()
            sid = proxy_provider.random_sid()
            if idp is None: # outbound packets from proxy inside the same domain as BR
                src_ip = str(proxy_provider.ip_address)
            pid_seq = PIDGen.gen_pids(nid, sid, sks=sk_list[-1:0:-1], pxs=px_list[::-1]) + [0]
            if back_pid:
                back_pids = PIDGen.gen_pids(sid.nsid, sid, sks=sk_list[0:-1], pxs=px_list)
                for i in range(num_overwrite):
                    pid_seq[-1-i] = back_pids[i]
            data = DATA(pid_pt=pid_pt, pids=pid_seq[0:-1], flags=flags, \
                seg_id=0, n_sid=sid.nsid.to_bytes(), l_sid=sid.lsid.to_bytes(), nid=nid.to_bytes(), \
                nid_provider=sid.nsid.to_bytes(), res_pid=pid_seq[-1]) / ('x' * pld_size)
            # compute hmac
            if is_odpfip: # outbound(odpfip, odpfip_nrpid): last hop is provider
                # create odc entry
                if odc_dict is None: # filter duplicate (nid, sid)
                    print("error: odc_dict should not be None")
                    exit(1)
                pids_hex = TrafficGen.__pids_to_hex_str(pid_seq[0:-1])
                if (sid, nid, pids_hex) in odc_dict.keys():
                    rn = odc_dict[(sid, nid, pids_hex)]
                else:
                    rn = random.getrandbits(32)
                    odc_dict[(sid, nid, pids_hex)] = rn
                    rn_hex = "%08X" % rn
                    odc_entries.append((str(sid.nsid), str(sid.lsid), str(nid), pids_hex, rn_hex))
                # the secret key of hmac
                sk = int.to_bytes(rn, length=4, byteorder='little')
            elif is_inbound: # inbound(idp2p, idp2nbr): last hop is eBR 
                last_hop = path[index_of_target_br - 1]
                sk = last_hop.sk_bytes()
            else: # outbound(odpfop): last hop is iBR
                last_hop = path[index_of_target_br - 2]
                sk = last_hop.sk_bytes()
            compute_hmac(data, sk)
            pkt = Ether() / IP(src=src_ip, dst=dst_ip) / data
            pkts.append(pkt)
        return pkts, odc_entries